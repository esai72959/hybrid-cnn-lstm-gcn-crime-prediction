"""
=========================================================
Project : A Hybrid CNN-LSTM Framework for Spatio-Temporal Crime Prediction
Module  : Data Preprocessing

Dataset :
Crimes_in_india_2001-2013.csv

Description :
This module performs data preprocessing on the crime dataset, resolving
the open issues flagged by the Phase 1 Dataset Readiness Report
(see eda.py): state-level aggregate rows disguised as districts,
inconsistent casing of state names, and the absence of an explicit
identifier column. The cleaned dataset produced here is the direct
input to Phase 3 (Feature Engineering).
=========================================================
"""

import os

import pandas as pd


class CrimeDataPreprocessor:
    """
    Cleans the district-level, multi-year IPC crime dataset in
    preparation for feature engineering.

    This class picks up exactly where the Phase 1 EDA (eda.py) left
    off: every cleaning step here corresponds to an open issue recorded
    in the Dataset Readiness Report, rather than being a fresh, separate
    pass over the data. Location columns, the year column, and the
    target column are named consistently with CrimeDataEDA so both
    modules stay in agreement about the schema.

    Attributes:
        filepath (str): Path to the raw source CSV file.
        results_dir (str): Directory where the preprocessing report is
            saved.
        output_path (str): Path where the cleaned dataset is written.
        df (pd.DataFrame): Working DataFrame, populated by
            load_dataset() and mutated in place by each cleaning step.
        location_columns (list[str]): State and district columns.
        year_column (str): Name of the year column.
        target_column (str): Aggregate crime count column.
        id_column (str): Name of the surrogate identifier column
            generated by generate_surrogate_identifier(). None until
            that step has run.
        cleaning_log (list[str]): Human-readable record of every
            corrective action taken, in the order it was applied. Used
            to build the preprocessing report so the report can never
            drift out of sync with what actually happened to the data.
    """

    TOTAL_ROW_PATTERN = "total"  # matched case-insensitively, substring

    def __init__(self, filepath: str, results_dir: str, output_path: str):
        self.filepath = filepath
        self.results_dir = results_dir
        self.output_path = output_path

        self.df = None

        self.location_columns = ["STATE/UT", "DISTRICT"]
        self.year_column = "YEAR"
        self.target_column = "TOTAL IPC CRIMES"
        self.id_column = None

        self.cleaning_log = []

        os.makedirs(self.results_dir, exist_ok=True)
        os.makedirs(os.path.dirname(self.output_path), exist_ok=True)

    # ------------------------------------------------------------------
    # Data Loading
    # ------------------------------------------------------------------
    def load_dataset(self) -> bool:
        """
        Loads the raw CSV file into a DataFrame. This is intentionally
        a fresh load from disk rather than reusing an object handed off
        from eda.py, so this module can also be run standalone as a
        Phase 2 script.

        Returns:
            bool: True if the dataset was loaded successfully, False
            otherwise.
        """
        try:
            self.df = pd.read_csv(self.filepath)
            print(f"Dataset loaded successfully from: {self.filepath}")
            return True
        except FileNotFoundError:
            print(f"ERROR: File not found at path: {self.filepath}")
        except pd.errors.EmptyDataError:
            print("ERROR: The CSV file is empty.")
        except pd.errors.ParserError as exc:
            print(f"ERROR: Failed to parse CSV file. Details: {exc}")
        return False

    # ------------------------------------------------------------------
    # Cleaning Steps
    # ------------------------------------------------------------------
    def remove_aggregate_rows(self) -> None:
        """
        Removes rows where the District column is actually a
        state-level (or union-territory-level) aggregate rather than a
        real district (e.g. 'TOTAL', 'ZZ TOTAL', 'DELHI UT TOTAL').

        The Phase 1 EDA only worked around these rows for charting
        purposes (see _get_analysis_view() in eda.py) and left the
        stored dataset untouched. This is the step that actually removes
        them, so every downstream phase can group by state or district
        without double-counting totals.
        """
        print("\n--- Removing Aggregate/Total Rows ---")
        try:
            district_col = self.location_columns[1]
            mask = self.df[district_col].str.contains(
                self.TOTAL_ROW_PATTERN, case=False, na=False
            )
            removed_count = int(mask.sum())

            if removed_count == 0:
                print("No state-level aggregate rows found. Nothing to remove.")
                return

            self.df = self.df.loc[~mask].reset_index(drop=True)
            print(f"Removed {removed_count} state-level aggregate rows from "
                  f"'{district_col}'.")
            self.cleaning_log.append(
                f"Removed {removed_count} state-level aggregate rows disguised "
                f"as districts in '{district_col}'."
            )
        except Exception as exc:
            print(f"ERROR while removing aggregate rows: {exc}")

    def standardize_state_names(self) -> None:
        """
        Trims whitespace and normalizes the casing of the state/UT
        column, so that variants like 'Bihar' and 'BIHAR' collapse into
        a single state. The Phase 1 EDA flagged this as inflating the
        apparent state count from 37 to 70 (see unique_states() in
        eda.py); this step is what actually fixes it in the stored data.
        """
        print("\n--- Standardizing State/UT Names ---")
        try:
            state_col = self.location_columns[0]
            before_count = self.df[state_col].nunique()

            self.df[state_col] = self.df[state_col].str.strip().str.upper()

            after_count = self.df[state_col].nunique()
            print(f"Unique state/UT labels before standardization: {before_count}")
            print(f"Unique state/UT labels after standardization: {after_count}")
            self.cleaning_log.append(
                f"Standardized '{state_col}' casing and whitespace, reducing "
                f"unique labels from {before_count} to {after_count}."
            )
        except Exception as exc:
            print(f"ERROR while standardizing state names: {exc}")

    def generate_surrogate_identifier(self) -> None:
        """
        Adds a surrogate 'Id' column, since this dataset - unlike the
        earlier single-year dataset - has no explicit identifier column
        (see check_identifier_column() in eda.py). The Id is a simple
        1-indexed row number assigned after aggregate rows have been
        removed, so it uniquely identifies each remaining district-year
        record for downstream phases (e.g. joining predictions back to
        source rows in Phase 10).
        """
        print("\n--- Generating Surrogate Identifier Column ---")
        try:
            self.id_column = "Id"
            self.df.insert(0, self.id_column, range(1, len(self.df) + 1))
            print(f"Added surrogate identifier column '{self.id_column}' "
                  f"({len(self.df)} rows).")
            self.cleaning_log.append(
                f"Generated surrogate identifier column '{self.id_column}', "
                "since the raw dataset had none."
            )
        except Exception as exc:
            print(f"ERROR while generating surrogate identifier: {exc}")

    def handle_missing_values(self) -> None:
        """
        Checks for missing values and fills any found in numeric crime
        columns with 0. The Phase 1 EDA reported no missing values in
        this dataset, so this step is expected to be a no-op in
        practice - it is kept here as a safeguard in case a future
        version of the source CSV introduces gaps, rather than assuming
        the absence of missing values will always hold.
        """
        print("\n--- Handling Missing Values ---")
        try:
            missing_counts = self.df.isnull().sum()
            total_missing = int(missing_counts.sum())

            if total_missing == 0:
                print("No missing values found. Nothing to handle.")
                return

            affected_columns = missing_counts[missing_counts > 0]
            print(f"Found {total_missing} missing values across "
                  f"{len(affected_columns)} column(s):")
            print(affected_columns)

            numeric_columns = self.df.select_dtypes(include="number").columns
            self.df[numeric_columns] = self.df[numeric_columns].fillna(0)
            print("Filled missing values in numeric columns with 0.")
            self.cleaning_log.append(
                f"Filled {total_missing} missing numeric values with 0 across "
                f"{len(affected_columns)} column(s)."
            )
        except Exception as exc:
            print(f"ERROR while handling missing values: {exc}")

    def remove_duplicate_rows(self) -> None:
        """
        Drops fully duplicated rows. The Phase 1 EDA reported zero
        duplicate rows in the raw dataset, but this check is re-run here
        rather than skipped, since duplicates can be introduced by
        earlier cleaning steps (e.g. two source rows differing only by
        state-name casing collapse into identical rows once
        standardize_state_names() has run).
        """
        print("\n--- Removing Duplicate Rows ---")
        try:
            duplicate_count = int(self.df.duplicated().sum())

            if duplicate_count == 0:
                print("No duplicate rows found. Nothing to remove.")
                return

            self.df = self.df.drop_duplicates().reset_index(drop=True)
            print(f"Removed {duplicate_count} duplicate rows.")
            self.cleaning_log.append(f"Removed {duplicate_count} duplicate rows.")
        except Exception as exc:
            print(f"ERROR while removing duplicate rows: {exc}")

    def validate_data_types(self) -> None:
        """
        Confirms that the year column and all crime/target columns are
        numeric, coercing them if necessary. This guards Phase 3
        (Feature Engineering) and the CNN/LSTM branches against silently
        treating a numeric column as text (e.g. if a stray non-numeric
        value slipped into a crime-count column upstream).
        """
        print("\n--- Validating Data Types ---")
        try:
            excluded = set(self.location_columns)
            if self.id_column is not None:
                excluded.add(self.id_column)
            numeric_expected = [c for c in self.df.columns if c not in excluded]

            coerced_columns = []
            for column in numeric_expected:
                if not pd.api.types.is_numeric_dtype(self.df[column]):
                    self.df[column] = pd.to_numeric(self.df[column], errors="coerce")
                    coerced_columns.append(column)

            if coerced_columns:
                print(f"Coerced {len(coerced_columns)} column(s) to numeric type: "
                      f"{coerced_columns}")
                self.df[coerced_columns] = self.df[coerced_columns].fillna(0)
                self.cleaning_log.append(
                    f"Coerced non-numeric values to numeric (filled with 0) in: "
                    f"{coerced_columns}."
                )
            else:
                print("All expected numeric columns already have a numeric dtype.")
        except Exception as exc:
            print(f"ERROR while validating data types: {exc}")

    # ------------------------------------------------------------------
    # Output
    # ------------------------------------------------------------------
    def save_cleaned_dataset(self) -> None:
        """
        Writes the cleaned DataFrame to self.output_path as a CSV file,
        ready to be consumed directly by Phase 3 (Feature Engineering)
        without re-running any of the cleaning steps above.
        """
        print("\n--- Saving Cleaned Dataset ---")
        try:
            self.df.to_csv(self.output_path, index=False)
            print(f"[Saved] Cleaned dataset -> {self.output_path} "
                  f"({self.df.shape[0]} rows, {self.df.shape[1]} columns)")
        except Exception as exc:
            print(f"ERROR while saving cleaned dataset: {exc}")

    def generate_preprocessing_report(self) -> None:
        """
        Compiles a Preprocessing Report from the cleaning_log built up
        during this run and writes it to
        results/preprocessing_report.md.

        This mirrors generate_readiness_report() in eda.py: rather than
        Phase 3 having to guess what was done to the data, every
        corrective action taken here is recorded in one place, generated
        from the same log the cleaning steps themselves populated - not
        re-typed by hand.
        """
        try:
            lines = []
            lines.append("# Preprocessing Report")
            lines.append("")
            lines.append("**Project:** A Hybrid CNN-LSTM Framework for Spatio-Temporal Crime Prediction")
            lines.append("**Phase:** 2 - Data Preprocessing")
            lines.append(f"**Source Dataset:** {self.filepath}")
            lines.append(f"**Cleaned Dataset:** {self.output_path}")
            lines.append(f"**Final Shape:** {self.df.shape[0]} rows x "
                          f"{self.df.shape[1]} columns")
            lines.append("")

            lines.append("## Actions Taken")
            if self.cleaning_log:
                for action in self.cleaning_log:
                    lines.append(f"- {action}")
            else:
                lines.append("- No corrective actions were necessary; the raw "
                              "dataset was already clean.")
            lines.append("")

            lines.append("## Identifier Column")
            if self.id_column is not None:
                lines.append(f"- `{self.id_column}` (surrogate, generated during "
                              "this phase).")
            else:
                lines.append("- Not generated in this run.")
            lines.append("")

            lines.append("## Readiness Verdict")
            lines.append("- **Ready for Phase 3 (Feature Engineering):** Yes - "
                          "all open issues from the Phase 1 Dataset Readiness "
                          "Report have been resolved and the cleaned dataset has "
                          "been persisted to disk.")
            lines.append("")

            report_text = "\n".join(lines)
            output_path = os.path.join(self.results_dir, "preprocessing_report.md")
            with open(output_path, "w") as report_file:
                report_file.write(report_text)

            print(f"\n[Saved] Preprocessing Report -> {output_path}")
            print("\n" + report_text)
        except Exception as exc:
            print(f"ERROR while generating preprocessing report: {exc}")

    # ------------------------------------------------------------------
    # Orchestration
    # ------------------------------------------------------------------
    def run_full_preprocessing(self) -> None:
        """
        Runs every preprocessing step in sequence. Each step is wrapped
        internally with its own exception handling, so a failure in one
        step does not prevent the remaining steps from running - the
        same pattern used by run_full_eda() in eda.py.
        """
        if not self.load_dataset():
            print("Stopping preprocessing: dataset could not be loaded.")
            return

        steps = [
            self.remove_aggregate_rows,
            self.standardize_state_names,
            self.generate_surrogate_identifier,
            self.handle_missing_values,
            self.remove_duplicate_rows,
            self.validate_data_types,
        ]

        for step in steps:
            try:
                step()
            except Exception as exc:
                print(f"ERROR: Step '{step.__name__}' failed: {exc}")

        self.save_cleaned_dataset()
        self.generate_preprocessing_report()


def main() -> None:
    """Entry point for running Phase 2 preprocessing as a standalone script."""
    dataset_path = os.path.join("dataset", "Crimes_in_india_2001-2013.csv")
    results_path = "results"
    output_path = os.path.join("dataset", "Crimes_in_india_2001-2013_cleaned.csv")

    preprocessor = CrimeDataPreprocessor(
        filepath=dataset_path, results_dir=results_path, output_path=output_path
    )
    preprocessor.run_full_preprocessing()


if __name__ == "__main__":
    main()
